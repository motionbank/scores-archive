jQuery(function(){
	window.motionbank = {
		app : new MotionBankLogoGenerator()
	}
});

var MotionBankLogoGenerator = (function(){

	/*
	 +	Private variables
	 +
	 L + + + + + + + + + + + + + + */

	 var app = null;

	 var thrRenderer, thrScene, thrContainer, thrCamera;
	 var follower;
	 var animator;

	 var generatorVersion = "001";

	/*
	 +	Private functions
	 +
	 L + + + + + + + + + + + + + + */

	var initThreeJs = function () {
		
		thrContainer = jQuery('#generator');
		width = thrContainer.width();
		height = thrContainer.height();

		if ( width == 0 || height == 0 ) {
			width  = thrContainer.get(0).clientWidth;
			height = thrContainer.get(0).clientHeight;
		}

		var rendererClass = undefined;
		if ( Detector.webgl ) {
			rendererClass = THREE.WebGLRenderer;
		} else if ( Detector.canvas ) {
			rendererClass = THREE.CanvasRenderer;
		} else {
			rendererClass = THREE.SoftwareRenderer;
		}

	 	thrRenderer = new rendererClass({
	 		antialias: true
	 	});
		thrRenderer.setSize( width, height );

		thrScene = new THREE.Scene();
		
		thrCamera = new THREE.PerspectiveCamera( 45, thrContainer.width()/thrContainer.height(), 0.1, 10000 );

		thrScene.add(thrCamera);
		// set camera to look at "stage"
		thrCamera.rotation.x = Math.PI;
		thrCamera.position.x = thrContainer.width()/2;
		thrCamera.position.y = thrContainer.height()/2;
		thrCamera.position.z = -600;

		thrContainer.append( thrRenderer.domElement );

		follower = new Pathfollower();
		follower.loadPath( 'data/box_02g.svg.json' );

		animator = new Animator({
			onUpdate: updateThreeJs,
			onRender: renderThreeJs,
			context: app
		});
		animator.start();
	}

	var updateThreeJs = function (t) {
		if ( follower.ready ) follower.update();
	}

	var renderThreeJs = function (t) {
		thrRenderer.render( thrScene, thrCamera );
	}

	var initInterface = function () {

		jQuery('#shapeChooser').change(function(){
			var val = $(this).val();
			follower.hidePath();
			follower.ready = false;
			follower = new Pathfollower();
			follower.loadPath('data/'+val+'.svg.json');
		});

		jQuery('#speedSlider').change(function(){
			follower.headSpeedTarg = this.value;
		});

		jQuery('#elasticitySlider').change(function(){
			follower.penBindingElasticityTarg = this.value / 1000.0;
		});

		jQuery('#lengthSlider').change(function(){
			follower.penBindingLengthTarg = this.value;
			//console.log( follower.penBindingLength );
		});

		jQuery('#massSlider').change(function(){
			follower.penMassTarg = this.value;
		});

		jQuery('#dampingSlider').change(function(){
			follower.penDampingTarg = this.value / 100.0;
		});

		jQuery('#resetButton').click(function(evt){
			evt.preventDefault();
			jQuery('#speedSlider').val(1).change();
			jQuery('#elasticitySlider').val(0.02 * 1000.0).change();
			jQuery('#lengthSlider').val(20).change();
			jQuery('#massSlider').val(10).change();
			jQuery('#dampingSlider').val(0.98 * 100.0).change();
			randomizeValues();
		}).click();

		jQuery('#saveButton').click(function(evt){
			evt.preventDefault();

			var pdfRenderer = new THREE.PDFRenderer();
			pdfRenderer.setSize( thrContainer.width(), thrContainer.height() );
			var pdf = pdfRenderer.getPDF();
			pdf.setTextColor( 0,0,0 );
			pdf.setFontSize( 8 );
			pdf.text( 5, thrContainer.height()-5, 
					 "Generated by vers. "+generatorVersion+" on "+new Date().toString() );
			pdfRenderer.render( thrScene, thrCamera );
			document.getElementById('saves').appendChild( pdfRenderer.domElement );

			pdfRenderer = null;
		});

		jQuery('#toggleButton').click(function(evt){
			evt.preventDefault();

			follower.toggleType();
		});
	}

	var sliders = {
		'speedSlider' : [],
		'elasticitySlider' : [],
		'lengthSlider' : [],
		'massSlider' : [],
		'dampingSlider' : [],
	};

	var randomizeValues = function () {
		var rnd = function (f) { return f * Math.random() };
		// for ( var s in sliders ) {
		// 	var $s = jQuery( '#'+s );
		// 	var mi = $s.attr('min'), ma = $s.attr('max');
		// 	var v = $s.val();
		// 	v = mi + rnd(ma-mi);
		// 	$s.val(v).change();
		// }
		jQuery('#speedSlider').val(0.1+rnd(2)).change();
		jQuery('#elasticitySlider').val(0.02 * 1000.0).change();
		jQuery('#lengthSlider').val(20+rnd(20)).change();
		jQuery('#massSlider').val(5+rnd(10)).change();
		jQuery('#dampingSlider').val(100-2.5-rnd(5)).change();
	}

	/*
	 +	Private class Pathfollower
	 +
	 L + + + + + + + + + + + + + + */

	 var Pathfollower = (function(){
	 	var follower = null;
		var Pathfollower = function () {

			var trailColor = 0x000000;

			if ( LocationParams ) {
				var locParams = new LocationParams();
				if ( locParams ) {
					if ( locParams['stroke'] ) {
						trailColor = parseInt( locParams['stroke'], 16 );
					}
				}
			}

			follower = this;

			this.path = null;
			this.thrPath = null;
			this.doShowPath = true;
			this.ready = false;

			this.currentSegment = 0;
			this.currentPoint = 0;
			this.currentPosition = {x:0,y:0};

			var showPenAndHead = false;

			// head
			// --------
			var mat = new THREE.MeshBasicMaterial({ 
				color:0x000055, 
				visible: showPenAndHead 
			});
			this.head = new THREE.Mesh(
				new THREE.PlaneGeometry( 5, 5, 1, 1 ),
				mat
			);
			this.head.rotation.x = Math.PI;
			thrScene.add( this.head );

			this.headSpeed = this.headSpeedTarg = 10;
			this.penBindingElasticity = this.penBindingElasticityTarg = 0.02;
			this.penMass = this.penMassTarg = 10;
			this.penDamping = this.penDampingTarg = 0.98;
			this.penBindingLength = this.penBindingLengthTarg = 20;

			// pen
			// ----------
			mat = new THREE.MeshBasicMaterial({ 
				color:0x005500, 
				visible: showPenAndHead 
			});
			this.pen = new THREE.Mesh(
				new THREE.PlaneGeometry( 5, 5, 1, 1 ),
				mat
			);
			this.pen.rotation.x = Math.PI;
			thrScene.add( this.pen );

			this.penVelocity = new THREE.Vector3(0,0,0);

			// trail
			// ---------
			this.trailLength = 10000;
			this.trailGeometry = new THREE.Geometry();
			this.trailColors = [];
			for ( var i = 0; i < this.trailLength; i++ ) {
				this.trailGeometry.vertices.push( new THREE.Vector3(
					thrContainer.width()/2,
					thrContainer.height()/2,
					0
				) );
				this.trailColors.push(
					new THREE.Color().setHSV( i/this.trailLength, 0.8, 0.8 )
				);
			}
			//this.trailGeometry.colors = this.trailColors;
			this.trail = new THREE.Line(
				this.trailGeometry,
				new THREE.LineBasicMaterial({
					color: trailColor,
					linewidth: 2, 
					//vertexColors: THREE.VertexColors
				})
			);
			thrScene.add( this.trail );
		};
		Pathfollower.prototype = {
			loadPath : function ( file ) {
				jQuery.ajax({
					url : file,
					dataType : 'json',
					success : function (arr) {
					if ( arr && arr.length > 0 ) {
						this.path = arr;
						this.thrPath = new THREE.Object3D();
						this.thrPath.name = "json_path";
						for ( var i = 0, k = this.path.length; i < k; i++ ) {
							var pathGeometry = new THREE.Geometry();
							var pArr = this.path[i];
							for ( var n = 0, m = pArr.length; n < m; n++ ) {
								pathGeometry.vertices.push( new THREE.Vector3( pArr[n].x, pArr[n].y, 0 ) );
							}
							this.thrPath.add( new THREE.Line( 
									pathGeometry, 
									new THREE.LineBasicMaterial({ 
										color: 0x999999, 
										linewidth: 1.1,
										visible: false
									}) 
								)
							)
						}
						this.currentPosition = arr[0][0];
						if ( this.doShowPath ) {
							thrScene.add( this.thrPath );
						}
						this.ready = true;
					}
					},
					error : function () {},
					context : follower
				});
			},
			update : function () {

				this.currentPoint = 0;
				this.currentSegment = 0;

				var damp = 30.0;
				this.headSpeed += (this.headSpeedTarg-this.headSpeed)/damp;
				this.penBindingElasticity += (this.penBindingElasticityTarg-this.penBindingElasticity)/damp;
				this.penMass += (this.penMassTarg-this.penMass)/damp;
				this.penDamping += (this.penDampingTarg-this.penDamping)/damp;
				this.penBindingLength += (this.penBindingLengthTarg-this.penBindingLength)/damp;

				var lastSegment = false, pathLength = this.path.length-1;
				do {
					this.updateImpl();
					if ( lastSegment === false ) {
						lastSegment = this.currentSegment === pathLength;
					}
				} while ( !(lastSegment && this.currentSegment == 0) );
			},
			updateImpl : function () {
				var force = this.pen.position.clone().subSelf(this.head.position);
				var d = force.length();

				//if ( d < this.penBindingLength ) {
					var vec = new THREE.Vector3( this.currentPosition.x, this.currentPosition.y, 0 );
					vec.subSelf( this.head.position );
					var dist = vec.length();
					if ( dist < follower.headSpeed ) {
						var pos = this.nextPosition();
					}
					vec.normalize();
					vec.multiplyScalar( follower.headSpeed );
					this.head.position.addSelf(vec);
				//}

				d = d - this.penBindingLength;
				force.normalize();
				force.multiplyScalar(d);
				force.multiplyScalar(-this.penBindingElasticity);
				force.divideScalar(this.penMass);
				this.penVelocity.addSelf(force);
				this.penVelocity.multiplyScalar(this.penDamping);
				this.pen.position.addSelf(this.penVelocity);

				this.trailGeometry.vertices.shift();
				this.trailGeometry.vertices.push( this.pen.position.clone() );
				this.trailGeometry.verticesNeedUpdate = true;
			},
			nextPosition : function () {
				if ( this.currentPoint >= this.path[this.currentSegment].length ) {
					this.currentSegment++;
					this.currentSegment %= this.path.length;
					this.currentPoint = 0;
				}
				this.currentPosition = this.path[this.currentSegment][this.currentPoint];
				this.currentPoint++;
				return this.currentPosition;
			},
			showPath : function () {
				if ( !this.doShowPath ) {
					thrScene.add( this.thrPath );
				}
				this.doShowPath = true;
			},
			hidePath : function () {
				if ( this.doShowPath ) {
					this.removePath();
					thrScene.remove( this.thrPath );
				}
				this.doShowPath = false;
			},
			removePath : function () {
    			//thrScene.remove( thrScene.getObjectByName( "json_path" ) );
    			var obj, i;
				for ( i = thrScene.children.length - 1; i >= 0 ; i -- ) {
				    obj = thrScene.children[ i ];
				    if ( obj !== thrCamera) {
				        thrScene.remove(obj);
				    }
				}
			},
			toggleType : function () {
				for ( var i = 0, k = this.thrPath.children.length; i < k; i++ ) {
					var child = this.thrPath.children[i];
					child.material.visible = !child.material.visible;
				}
			},
			setTypeVisibility : function ( visible ) {
				for ( var i = 0, k = this.thrPath.children.length; i < k; i++ ) {
					var child = this.thrPath.children[i];
					child.material.visible = visible;
				}
			}
		};
		return Pathfollower;
	})();

	/*
	 +	Class MotionBankLogoGenerator
	 +
	 L + + + + + + + + + + + + + + */

	var App = function(){
		app = this;
		initThreeJs();
		initInterface();
	};
	App.prototype = {
		randomize : function(){
			randomizeValues();
		}
	};
	return App;
})();